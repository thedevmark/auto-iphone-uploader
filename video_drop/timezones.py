def zone(name: str) -> ZoneInfo:
    """An IANA time zone by name, or a plain error the settings screen can show."""
    if not isinstance(name, str) or not name.strip():
        raise ValueError("Choose a time zone")
    try:
        return ZoneInfo(name.strip())
    except (ZoneInfoNotFoundError, ValueError) as exc:
        raise ValueError(f"Unknown time zone: {name.strip()[:60]}") from exc


def valid_zone_name(name: str) -> bool:
    try:
        zone(name)
    except ValueError:
        return False
    return True


def windows_zone_key() -> str | None:
    """The zone Windows is set to, e.g. "Eastern Standard Time"."""
    if os.name != "nt":
        return None
    import winreg

    try:
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                            r"SYSTEM\CurrentControlSet\Control\TimeZoneInformation") as key:
            value = winreg.QueryValueEx(key, "TimeZoneKeyName")[0]
    except OSError:
        return None
    # Some Windows builds leave padding after the name.
    return str(value).split("\x00", 1)[0].strip() or None


def posix_zone_name(env: Mapping[str, str] = os.environ) -> str | None:
    configured = str(env.get("TZ", "")).lstrip(":")
    if configured and valid_zone_name(configured):
        return configured
    try:
        target = os.path.realpath("/etc/localtime")
    except OSError:
        return None
    name = target.split("zoneinfo/", 1)[1] if "zoneinfo/" in target else ""
    return name if name and valid_zone_name(name) else None


def pc_zone_name() -> str | None:
    """The IANA name of this PC's time zone, or None when it cannot be named."""
    if os.name == "nt":
        name = WINDOWS_ZONES.get(windows_zone_key() or "")
        return name if name and valid_zone_name(name) else None
    return posix_zone_name()


def pc_time_zone() -> tzinfo:
    """This PC's time zone; a fixed current offset only when the zone has no IANA name."""
    name = pc_zone_name()
    return ZoneInfo(name) if name else datetime.now().astimezone().tzinfo


def zone_key(value: tzinfo) -> str:
    """The IANA name of a zone, or "" for a fixed offset."""
    return str(getattr(value, "key", "") or "")
